const GOOGLE_HOST_SET = new Set(GOOGLE_HOSTS);

/** True for a Google search portal or one of its result-serving subdomains. */
export function isGoogleSearchHost(hostname: string): boolean {
  const host = hostname.toLowerCase();
  if (GOOGLE_HOST_SET.has(host)) return true;
  // One leading www. is the portal itself in most locales.
  if (host.startsWith("www.") && GOOGLE_HOST_SET.has(host.slice(4))) return true;
  // News uses a dedicated subdomain in most locales (news.google.com,
  // news.google.co.uk, …). The suffix must itself be a REAL Google host:
  // `news.google.` + anything would also accept news.google.com.attacker.tld,
  // and this predicate is the origin check for replayed (page-controlled)
  // fetch requests — a lookalike host would defeat that gate.
  if (host.startsWith("news.") && GOOGLE_HOST_SET.has(host.slice("news.".length))) return true;
  return host === "encrypted.google.com";
}
